// Extract keywords from title and content
const extractKeywordsFromTitle = (title: string): string[] => {
  const keywords: string[] = [];
  
  // Common pet-related terms
  const petTerms = ['狗狗', '貓貓', '貓咪', '毛孩', '寵物', '主子', '主子', '主子'];
  const healthTerms = ['健康', '疾病', '症狀', '治療', '預防', '護理', '保健'];
  const actionTerms = ['如何', '點樣', '方法', '貼士', '指南', '攻略', '必讀', '懶人包'];
  
  // Extract from title
  title.split(/[|｜]/).forEach(part => {
    part.split(/[，,、\s]/).forEach(word => {
      const trimmed = word.trim();
      if (trimmed.length > 1 && trimmed.length < 10) {
        keywords.push(trimmed);
      }
    });
  });
  
  return keywords;
};

// Generate comprehensive keywords for a blog post
export const generateBlogKeywords = (post: BlogPost): string => {
  const keywords: string[] = [];
  
  // Add custom keywords if provided
  if (post.seoKeywords && post.seoKeywords.length > 0) {
    keywords.push(...post.seoKeywords);
  }
  
  // Add category-specific keywords
  if (categoryKeywords[post.category]) {
    keywords.push(...categoryKeywords[post.category]);
  }
  
  // Extract from title
  keywords.push(...extractKeywordsFromTitle(post.title));
  
  // Add common base keywords
  keywords.push(
    'PetWell', 'PetWell HK', '香港寵物', '寵物主人', '養寵物', '寵物資訊',
    '寵物知識', '寵物貼士', '寵物指南', '寵物攻略', '寵物建議'
  );
  
  // Add location-specific
  keywords.push('香港', 'HK', 'Hong Kong');
  
  // Remove duplicates and join
  return Array.from(new Set(keywords)).join(',');
};

