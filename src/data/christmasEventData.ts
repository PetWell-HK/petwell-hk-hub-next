export const getEventById = (id: string): ChristmasEvent | undefined => {
  return christmasEvents.find(event => event.id === id);
};

// Helper function to shuffle an array using Fisher-Yates algorithm
const shuffleArray = <T,>(array: T[]): T[] => {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
};

// Get randomly selected events for a personality (max 5)
export const getRandomEventsByPersonality = (personality: Personality, maxEvents: number = 5): ChristmasEvent[] => {
  const matchingEvents = christmasEvents.filter(event => 
    event.recommendedFor.includes(personality)
  );
  
  if (matchingEvents.length <= maxEvents) {
    return matchingEvents;
  }
  
  // Shuffle and take first maxEvents
  return shuffleArray(matchingEvents).slice(0, maxEvents);
};

// Get all events for a personality (no limit) - kept for backwards compatibility
export const getAllEventsByPersonality = (personality: Personality): ChristmasEvent[] => {
  return christmasEvents.filter(event => 
    event.recommendedFor.includes(personality)
  );
};
